"""Summarize evaluation changes without importing PyTorch or launching KataGo."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import tempfile


MARKER = "<!-- generated by report_evaluation.py -->"


def _percent(value):
    return "—" if value is None else f"{value * 100:.1f}%"


def _number(value):
    return "—" if value is None else f"{value:.3f}"


def _pool_score(summary: dict, name: str):
    for row in summary.get("opponent_pool", {}).get("opponents", []):
        if row["opponent"] == name:
            return f"{_percent(row['score_rate'])} ({row['games']}局)"
    return "—"


def render(run: Path) -> str:
    paths = sorted((run / "iterations").glob("*/summary.json"))
    if not paths:
        raise ValueError("This run has no completed iteration summaries")
    summaries = [json.loads(path.read_text(encoding="utf-8")) for path in paths]
    samples = [
        "| 轮次 | 累计更新 | 回放样本 | KataGo 着法负对数概率↓ | 首选着法一致率↑ | 原分析中的目差覆盖 | 补测后的平均带符号目差↓ |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    matches = [
        "| 轮次 | 均匀策略 MCTS | 固定初始模型 | 初筛 | 晋级对战 | 晋级 |",
        "| ---: | ---: | ---: | ---: | --- | --- |",
    ]
    training_opponents = [
        "| 轮次 | 候选自我对弈 | 冻结对手对局 | 对手版本 |",
        "| ---: | ---: | ---: | --- |",
    ]
    protocols = set()
    for path, summary in zip(paths, summaries):
        quality = summary.get("position_quality", {})
        group = quality.get("groups", {}).get("all", {})
        complete_score_path = path.parent / "katago_score_complete.json"
        full_score = None
        if complete_score_path.is_file():
            scored = json.loads(complete_score_path.read_text(encoding="utf-8"))
            if (scored.get("candidate_sha256") == summary.get("model_sha256")
                    and scored.get("suite_sha256") == quality.get("suite_sha256")
                    and (not quality.get("teacher_labels_sha256") or
                         scored.get("teacher_sha256") == quality["teacher_labels_sha256"])):
                full_score = scored["groups"]["all"]["mean_reference_delta_points"]
        if quality.get("status") == "measured":
            protocols.add((quality.get("suite_sha256"), quality.get("teacher_labels_sha256"),
                           quality.get("teacher_model_sha256"),
                           quality.get("teacher_engine_sha256"), quality.get("teacher_config_sha256"),
                           quality.get("teacher_visits"), quality.get("candidate_visits")))
        samples.append(
            f"| {summary['iteration']} | {summary['training_steps']} | {summary['replay_samples']} | "
            f"{_number(group.get('mean_teacher_log_loss'))} | "
            f"{_percent(group.get('teacher_top_move_rate'))} | "
            f"{group.get('score_delta_coverage', '—')}/{group.get('positions', '—')} | "
            f"{_number(full_score)} |"
        )
        screening = summary.get("screening", {})
        evaluation = summary.get("evaluation", {})
        if "paired" in evaluation:
            paired = evaluation["paired"]
            if evaluation.get("promotion_test") == "paired_sign":
                sign = evaluation["paired_sign"]
                result = (f"{_percent(evaluation['score_rate'])} ({evaluation['games']}局，"
                          f"换色开局优势/劣势/持平 {sign['wins']}/{sign['losses']}/{sign['ties']}，"
                          f"单侧 p={sign['p_value']:.4f}，截断 {evaluation['truncated']}局)")
            else:
                result = (f"{_percent(evaluation['score_rate'])} ({evaluation['games']}局，"
                          f"区间 {_percent(paired['lower'])}～{_percent(paired['upper'])})")
        else:
            result = evaluation.get("status", "—")
        matches.append(
            f"| {summary['iteration']} | {_pool_score(summary, 'uniform_policy_mcts')} | "
            f"{_pool_score(summary, 'accepted_000000')} | "
            f"{_percent(screening.get('score_rate'))} | {result} | "
            f"{'是' if summary.get('promoted') else '否'} |"
        )
        opponents = summary.get("selfplay_opponents")
        if opponents is None:
            training_opponents.append(f"| {summary['iteration']} | — | — | 旧版记录缺少对手信息 |")
        else:
            self_games = sum(row["games"] for row in opponents
                             if row["name"] == "candidate_self")
            champions = [row for row in opponents if row["name"] != "candidate_self"]
            count = sum(row["games"] for row in champions)
            labels = "、".join(f"{row['name']} ({row['games']}局)" for row in champions) or "—"
            training_opponents.append(
                f"| {summary['iteration']} | {self_games}局 | {count}局 | {labels} |"
            )
    explanation = (
        "KataGo 指标来自同一组局面、老师模型和候选搜索预算。负对数概率下降及首选着法"
        "一致率上升仅表示更贴近该老师的策略，整体棋力仍需看固定对手的换色对战。\n\n"
        "原分析目差只覆盖 KataGo 搜索过的候选着法；补测后平均目差来自同一候选落子后"
        "局面的额外搜索，其中完全终局使用面积计分。该带符号指标仍受搜索噪声和 "
        "KataGo 首选着法兼顾胜率的影响。对手池比赛局数少时，单次胜率和区间"
        "都可能剧烈波动。"
    )
    if len(protocols) > 1:
        explanation += ("\n\n**注意：评测局面、KataGo 配置或候选搜索预算记录不一致。**"
                        "部分较旧的报告可能缺少协议字段；先核对设置，再比较局面诊断趋势。")
    return "\n".join([
        MARKER, "# 9×9 训练评测趋势", "",
        f"运行目录：`{run}`。已完成 {len(summaries)} 轮。", "",
        "## 训练对手", "", *training_opponents, "",
        "## 固定局面", "", *samples, "", "## 换色对战", "", *matches,
        "", explanation, "",
    ])


def write_report(path: Path, content: str) -> None:
    if path.exists() and not path.read_text(encoding="utf-8").startswith(MARKER):
        raise ValueError("Report path contains a file not generated by this command")
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="Show how fixed-position and opponent metrics change by iteration")
    parser.add_argument("--run", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    try:
        output = args.output or args.run / "evaluation_trend.md"
        write_report(output, render(args.run))
        print(output)
    except (ValueError, OSError, KeyError, TypeError) as error:
        parser.exit(1, f"Report error: {error}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
